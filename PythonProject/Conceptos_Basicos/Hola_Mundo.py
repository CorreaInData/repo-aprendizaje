# Variables de Python y conceptos básicos (impresión en consola, operaciones y comentarios)

num = 10    # Python permite la creación de variables númericas
print(num)
print(type(num))
print("")

cadena = 'Anita lava la "tina"' # Variables de texto
print(cadena)
print(type(cadena))
print("")

afirmacion = True   # Variables Booleanas
print(afirmacion)
print(type(afirmacion))
print("")

num1 = 10
num2 = 6.7
resultado = (num1 + num2) * 10 / 6    # Así mismo, Python permite la operación entre variables y números fijos

print("El resultado es: ",resultado)
print(type(resultado))
print("")

